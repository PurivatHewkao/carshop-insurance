-- Car Shop: MySQL 8.0.16+ / 8.4. Run on a new local database.
-- No DROP, DELETE, seed credentials or automatic migration.
-- UUIDs must be generated and validated by the backend (crypto.randomUUID()).
-- This is a single local SQL database with foreign keys, not isolated service databases.
CREATE DATABASE IF NOT EXISTS carshop_sql CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE carshop_sql;
SET time_zone = '+00:00';

CREATE TABLE IF NOT EXISTS users (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  username VARCHAR(100) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('CUSTOMER','SELLER','ADMIN','MANAGER','FINANCE','STOCK') NOT NULL DEFAULT 'CUSTOMER',
  status ENUM('ACTIVE','INACTIVE') NOT NULL DEFAULT 'ACTIVE',
  email VARCHAR(254) NOT NULL UNIQUE,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS customers (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  user_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
  first_name VARCHAR(100) NOT NULL,
  last_name VARCHAR(100) NOT NULL,
  phone_number VARCHAR(30) NULL,
  email VARCHAR(254) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS employees (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  user_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
  department_name VARCHAR(100) NULL,
  first_name VARCHAR(100) NOT NULL,
  last_name VARCHAR(100) NOT NULL,
  position_name VARCHAR(100) NULL,
  phone_number VARCHAR(30) NULL,
  hire_date DATE NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS car_models (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  brand VARCHAR(100) NOT NULL,
  model_name VARCHAR(150) NOT NULL,
  body_type VARCHAR(50) NULL,
  description TEXT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS cars (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  car_model_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  vin VARCHAR(17) NOT NULL UNIQUE,
  license_plate VARCHAR(30) NULL UNIQUE,
  color VARCHAR(50) NOT NULL,
  manufacture_year SMALLINT UNSIGNED NOT NULL,
  price DECIMAL(14,2) NOT NULL,
  status ENUM('AVAILABLE','RESERVED','SOLD','INACTIVE') NOT NULL DEFAULT 'AVAILABLE',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (car_model_id) REFERENCES car_models(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CHECK (price >= 0),
  CHECK (manufacture_year BETWEEN 1886 AND 9999)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS car_images (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  car_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  image_path VARCHAR(2048) NOT NULL,
  sort_order INT UNSIGNED NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (car_id) REFERENCES cars(id) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS promotions (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  title VARCHAR(200) NOT NULL,
  description TEXT NULL,
  discount_type ENUM('FIXED','PERCENT') NOT NULL,
  discount_value DECIMAL(14,2) NOT NULL,
  start_date DATETIME(3) NOT NULL,
  end_date DATETIME(3) NOT NULL,
  status ENUM('ACTIVE','INACTIVE') NOT NULL DEFAULT 'ACTIVE',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  CHECK (discount_value >= 0),
  CHECK (discount_type <> 'PERCENT' OR discount_value <= 100),
  CHECK (end_date >= start_date)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS appointments (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  customer_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  car_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  seller_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  appointment_type ENUM('VIEW_CAR','TEST_DRIVE') NOT NULL,
  appointment_date DATE NOT NULL,
  appointment_time TIME NOT NULL,
  status ENUM('PENDING','CONFIRMED','COMPLETED','CANCELLED') NOT NULL DEFAULT 'PENDING',
  note TEXT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  INDEX idx_appointments_seller_date (seller_id, appointment_date, appointment_time),
  FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  FOREIGN KEY (car_id) REFERENCES cars(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  FOREIGN KEY (seller_id) REFERENCES employees(id) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS assignments (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  customer_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  seller_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  assigned_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  assigned_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  status ENUM('ACTIVE','COMPLETED','CANCELLED') NOT NULL DEFAULT 'ACTIVE',
  note TEXT NULL,
  FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  FOREIGN KEY (seller_id) REFERENCES employees(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  FOREIGN KEY (assigned_by) REFERENCES employees(id) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS orders (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  customer_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  seller_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  car_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  promotion_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  order_date DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  subtotal DECIMAL(14,2) NOT NULL,
  discount DECIMAL(14,2) NOT NULL DEFAULT 0,
  total_amount DECIMAL(14,2) NOT NULL,
  status ENUM('PENDING','CONFIRMED','PAID','COMPLETED','CANCELLED') NOT NULL DEFAULT 'PENDING',
  active_car_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin GENERATED ALWAYS AS (CASE WHEN status <> 'CANCELLED' THEN car_id ELSE NULL END) STORED,
  UNIQUE KEY uq_orders_active_car (active_car_id),
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  INDEX idx_orders_customer_date (customer_id, created_at, id),
  FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  FOREIGN KEY (seller_id) REFERENCES employees(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  FOREIGN KEY (car_id) REFERENCES cars(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  FOREIGN KEY (promotion_id) REFERENCES promotions(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CHECK (subtotal >= 0),
  CHECK (discount >= 0 AND discount <= subtotal),
  CHECK (total_amount = subtotal - discount)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS payments (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  order_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  amount DECIMAL(14,2) NOT NULL,
  payment_method ENUM('CASH','BANK_TRANSFER','CREDIT_CARD') NOT NULL,
  payment_date DATETIME(3) NULL,
  status ENUM('PENDING','SUCCESS','FAILED','REFUNDED') NOT NULL DEFAULT 'PENDING',
  transaction_reference VARCHAR(150) NULL UNIQUE,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CHECK (amount > 0)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS invoices (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  order_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  issued_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  invoice_number VARCHAR(100) NOT NULL UNIQUE,
  issue_date DATE NOT NULL,
  due_date DATE NULL,
  amount DECIMAL(14,2) NOT NULL,
  status ENUM('ISSUED','PAID','CANCELLED') NOT NULL DEFAULT 'ISSUED',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  FOREIGN KEY (issued_by) REFERENCES employees(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CHECK (amount >= 0),
  CHECK (due_date IS NULL OR due_date >= issue_date)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS insurances (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  insurance_company VARCHAR(200) NOT NULL,
  insurance_name VARCHAR(200) NOT NULL,
  coverage TEXT NOT NULL,
  premium DECIMAL(14,2) NOT NULL,
  description TEXT NULL,
  status ENUM('ACTIVE','INACTIVE') NOT NULL DEFAULT 'ACTIVE',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  CHECK (premium >= 0)
) ENGINE=InnoDB;

SHOW TABLES;
